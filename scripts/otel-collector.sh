#!/usr/bin/env bash
#
# OTel collector lifecycle for the geode test harness.
#
# Spins up an otel/opentelemetry-collector-contrib Docker container with the
# `debug` exporter so spans + metrics emitted by the geode server during
# `make test-everything` are visible (and captured to a file) without needing
# a live GitLab Observability collector.
#
# Subcommands:
#   start   pull image (if needed) + run container, wait for OTLP/HTTP listener
#   stop    docker rm -f and clean up env files
#   logs    cat the captured collector log
#   tail    docker logs -f for live spans
#   verify  assert at least one span carrying service.name=geode arrived
#
# Defaults to non-conflicting ports 44317/44318 so a host-resident collector
# can keep running. Override via OTEL_COLLECTOR_HTTP_PORT / OTEL_COLLECTOR_GRPC_PORT.
#
# After `start`, downstream callers should source `.otel-env` (written into
# REPORT_DIR) to pick up OTEL_EXPORTER_OTLP_ENDPOINT, OTEL_TRACES_EXPORTER=otlp,
# etc.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPORT_DIR="${REPORT_DIR:-$ROOT/reports}"
HTTP_PORT="${OTEL_COLLECTOR_HTTP_PORT:-44318}"
GRPC_PORT="${OTEL_COLLECTOR_GRPC_PORT:-44317}"
IMAGE="${OTEL_COLLECTOR_IMAGE:-otel/opentelemetry-collector-contrib:0.96.0}"
CONTAINER="${OTEL_COLLECTOR_CONTAINER:-geode-harness-otel-collector}"
CFG="$REPORT_DIR/.otel-collector.yaml"
ENV_FILE="$REPORT_DIR/.otel-env"
LOG_FILE="$REPORT_DIR/otel-collector.log"

write_env_file() {
  cat > "$ENV_FILE" <<EOF
# Auto-generated by scripts/otel-collector.sh start
# Source this file before running geode + tests:
#   set -a; source $ENV_FILE; set +a
export OTEL_EXPORTER_OTLP_ENDPOINT="http://127.0.0.1:${HTTP_PORT}"
export OTEL_EXPORTER_OTLP_PROTOCOL="http/protobuf"
export OTEL_TRACES_EXPORTER="otlp"
export OTEL_METRICS_EXPORTER="otlp"
export OTEL_TRACES_SAMPLER="always_on"
export OTEL_BSP_SCHEDULE_DELAY="2000"
export OTEL_METRIC_EXPORT_INTERVAL="3000"
export OTEL_RESOURCE_ATTRIBUTES="service.name=geode,service.namespace=geode-test-harness,deployment.environment.name=harness"
EOF
}

write_collector_config() {
  cat > "$CFG" <<'YAML'
receivers:
  otlp:
    protocols:
      http:
        endpoint: 0.0.0.0:4318
      grpc:
        endpoint: 0.0.0.0:4317
exporters:
  debug:
    verbosity: detailed
  file:
    path: /var/log/otel/spans.jsonl
    rotation:
      max_megabytes: 64
      max_backups: 3
processors:
  batch: {}
service:
  telemetry:
    logs:
      level: info
  pipelines:
    traces:
      receivers: [otlp]
      processors: [batch]
      exporters: [debug, file]
    metrics:
      receivers: [otlp]
      processors: [batch]
      exporters: [debug, file]
YAML
}

require() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ERROR: required tool not found: $1" >&2
    exit 2
  }
}

cmd_start() {
  require docker
  mkdir -p "$REPORT_DIR"

  if docker ps --format '{{.Names}}' | grep -q "^${CONTAINER}$"; then
    echo "OTel collector container already running: $CONTAINER"
  else
    if docker ps -a --format '{{.Names}}' | grep -q "^${CONTAINER}$"; then
      docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
    fi
    write_collector_config
    : > "$LOG_FILE"

    echo "Starting OTel collector ($IMAGE) on :${HTTP_PORT}/${GRPC_PORT}..."
    docker run -d --rm \
      --name "$CONTAINER" \
      -p "${HTTP_PORT}:4318" \
      -p "${GRPC_PORT}:4317" \
      -v "${CFG}:/etc/otelcol-contrib/config.yaml:ro" \
      -v "${REPORT_DIR}:/var/log/otel" \
      "$IMAGE" >/dev/null

    # Wait for the HTTP listener (max ~10s).
    local i=0
    while [[ $i -lt 20 ]]; do
      if (echo > "/dev/tcp/127.0.0.1/${HTTP_PORT}") 2>/dev/null; then
        break
      fi
      sleep 0.5
      i=$((i + 1))
    done
    if [[ $i -ge 20 ]]; then
      echo "ERROR: collector did not bind to :${HTTP_PORT} within 10s" >&2
      docker logs "$CONTAINER" 2>&1 | tail -30 | sed 's/^/  /' >&2
      exit 1
    fi
  fi

  write_env_file
  echo "OTel collector ready."
  echo "  endpoint:    http://127.0.0.1:${HTTP_PORT}"
  echo "  env file:    $ENV_FILE"
  echo "  spans/jsonl: $REPORT_DIR/spans.jsonl (file exporter)"
  echo "  live logs:   $0 tail   |   stop: $0 stop"
}

cmd_stop() {
  require docker
  if docker ps -a --format '{{.Names}}' | grep -q "^${CONTAINER}$"; then
    echo "Stopping OTel collector ($CONTAINER)..."
    # Drain final log to disk before kill.
    docker logs "$CONTAINER" > "$LOG_FILE" 2>&1 || true
    docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
  else
    echo "OTel collector not running."
  fi
  rm -f "$ENV_FILE" "$CFG" 2>/dev/null || true
}

cmd_logs() {
  require docker
  # Prefer live container logs when running; fall back to the disk drain
  # written by cmd_stop.
  if docker ps --format '{{.Names}}' | grep -q "^${CONTAINER}$"; then
    docker logs "$CONTAINER" 2>&1
  elif [[ -f "$LOG_FILE" ]]; then
    cat "$LOG_FILE"
  else
    echo "No collector log found at $LOG_FILE — start the collector first." >&2
    exit 1
  fi
}

cmd_tail() {
  require docker
  docker logs -f "$CONTAINER"
}

cmd_verify() {
  require docker
  local got
  got="$(docker logs "$CONTAINER" 2>&1)"
  local ok=1
  if grep -qE 'service\.name.*geode|"service\.name":\s*"geode"' <<<"$got"; then
    echo "  ✓ at least one span/metric arrived with service.name=geode"
  else
    echo "  ✗ no service.name=geode records in collector output" >&2
    ok=0
  fi
  if grep -qiE 'metric|geode\.' <<<"$got"; then
    echo "  ✓ collector received geode metrics/spans"
  else
    echo "  ✗ no geode metric records observed" >&2
    ok=0
  fi
  if [[ $ok -eq 0 ]]; then
    echo ""
    echo "Last 80 lines of collector output:" >&2
    docker logs "$CONTAINER" 2>&1 | tail -80 | sed 's/^/  /' >&2
    exit 1
  fi
}

case "${1:-}" in
  start)  cmd_start ;;
  stop)   cmd_stop ;;
  logs)   cmd_logs ;;
  tail)   cmd_tail ;;
  verify) cmd_verify ;;
  *)
    echo "Usage: $0 {start|stop|logs|tail|verify}" >&2
    exit 2
    ;;
esac
